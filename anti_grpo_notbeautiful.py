def dino_group(images):
  # in-group diversity: 1 - mean DINOv3 CLS cosine of each image with the rest of the group's valid images
  with torch.inference_mode():
    emb = torch.nn.functional.normalize(dino_model(**dino_processor(images=images, return_tensors="pt").to("cuda")).pooler_output, dim=-1)
  n = len(images)
  return (1 - ((emb @ emb.T).sum(1) - 1) / (n - 1)).tolist()


