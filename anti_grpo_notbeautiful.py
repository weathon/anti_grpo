def reward_func(completions, concept, log_extra=None, log_metric=None, **kwargs):
    print(completions)
    formatted = format_reward(completions)
    images = [gen_image([p[1], p[2]]) if p[0] else None for p in formatted]
    valid = [img is not None for img in images]

    # one OpenRouter decider call per image answers both the related (itm) and validity questions
    itm_validity = [itm_reward(img, c) if ok else [0, 0]
                    for img, c, ok in zip(images, concept, valid)]
    itm_rewards = [r[0] for r in itm_validity]
    validity_rewards = [r[1] for r in itm_validity]
    hps_scores = [hps_score(img, f"an image of {c}") if ok else None
                  for img, c, ok in zip(images, concept, valid)]

    valid_imgs = [img for img, ok in zip(images, valid) if ok]
    group_valid = dino_group(valid_imgs) if len(valid_imgs) > 1 else []
    div_valid = iter(group_valid)
    diversity_rewards = [next(div_valid) if ok and group_valid else 0.0 for ok in valid]

    # 7 references sampled once per step from all previous steps' valid images (the decider allows 8 images per question); 0 while there is no history
    refs = random.sample(hist_bank, min(7, len(hist_bank)))
    hist_rewards = [hist_reward_openrouter(refs, img) if ok and refs else 0.0 for img, ok in zip(images, valid)]
    for img in valid_imgs:
      buf = io.BytesIO()
      img.resize((512, 512)).save(buf, format="PNG")
      hist_bank.append(base64.b64encode(buf.getvalue()).decode("ascii"))

    # first half of training: additive reward; second half: itm/validity gate the rest
    state = kwargs["trainer_state"]
    gate = state.global_step >= state.max_steps // 2

    if wandb.run:
        wandb.log({"images": [
            wandb.Image(images[i], caption=f"itm: {itm_rewards[i]}, validity: {validity_rewards[i]}, hps: {hps_scores[i]}, concept: {concept[i]}, diversity_rewards: {diversity_rewards[i]}, hist_diversity: {hist_rewards[i]}")
            for i in range(len(images)) if valid[i]
            ],
            # images holds None for invalid completions, which make_image_grid cannot paste; grid only the valid ones
            "whole_image": wandb.Image(make_image_grid(valid_imgs, 1, len(valid_imgs)), caption=f"concept: {concept[0]}") if valid_imgs else None,
            "valid": np.mean([i for i in valid if i is not None]),
            "itm": np.mean([i for i in itm_rewards if i is not None]),
            "img_validity": np.mean([i for i in validity_rewards if i is not None]),
            "hps": np.mean([i for i in hps_scores if i is not None]),
            "group_diversity": np.max([i for i in diversity_rewards if i is not None]),
            "hist_diversity": np.mean(hist_rewards),
            # mean pairwise DINOv3 cosine within the group's valid images
            "group_dino_sim": 1 - np.mean(group_valid) if group_valid else None,
            "gate": int(gate)
        })

    print(itm_rewards, validity_rewards, hps_scores, diversity_rewards, hist_rewards)

    rewards = []
    for i_r, v, h, d, hd, ok in zip(itm_rewards, validity_rewards, hps_scores, diversity_rewards, hist_rewards, valid):
        if not ok:
            rewards.append(-5)
        elif gate:
            # mean of itm and validity times the rest; HPS term shifted to hps_weight * (1 - clip(hps)/15) / 2, in [0, 3], so the rest is never negative
            rewards.append((i_r + v) / 2 * (hps_weight * (1 - clip_hpsv3(h)/15) / 2 + diversity_weight * d + hist_weight * hd))
        else:
            rewards.append(itm_weight * i_r + validity_weight * v + hps_weight * (-clip_hpsv3(h)/15) + diversity_weight * d + hist_weight * hd)

    return rewards

